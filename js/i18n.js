/* the legacy name stays pointed at English - tests and tooling read it */
const T = T_EN;

function t(k, vars){
  const lt = (typeof S!=='undefined' && S && S.lang==='lt');
  let s = (lt && T_LT[k]!=null ? T_LT[k] : T_EN[k]) || k;
  if(vars) for(const v in vars) s = s.replace('{'+v+'}', vars[v]);
  return s;
}
